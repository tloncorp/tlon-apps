#!/usr/bin/env node
// Post-build step (the packages/editor `editorHtml.ts` precedent): wrap
// the built artifact files in an importable module so packages/app can
// embed them as strings on every platform (metro and vite both resolve
// plain JS + d.ts without needing raw-loader support). The embedded
// artifact is the ONLY shell delivery path — never fetched at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const distDir = join(fileURLToPath(import.meta.url), '..', '..', 'dist');

const js = readFileSync(join(distDir, 'surface-shell.js'), 'utf8');
const css = readFileSync(join(distDir, 'surface-shell.css'), 'utf8');
// Read the version from its SOURCE, not by regexing the built artifact.
// Regexing dist was always the wrong authority and minification exposed
// it: `SHELL_VERSION = 1` becomes `SHELL_VERSION=1`, the pattern missed,
// and the `?? '0'` fallback reported version 0 — a failure that looked
// like a value, silently, to everything gating on the constant.
const versionSource = readFileSync(
  join(fileURLToPath(import.meta.url), '..', '..', 'src', 'version.ts'),
  'utf8'
);
const versionMatch = versionSource.match(/SHELL_VERSION\s*=\s*(\d+)/);
if (!versionMatch) {
  // No fallback: an unreadable version is a build failure, not a zero.
  console.error(
    'emit-artifact-module: could not read SHELL_VERSION from src/version.ts'
  );
  process.exit(1);
}
const version = versionMatch[1];

writeFileSync(
  join(distDir, 'artifactStrings.js'),
  [
    '// GENERATED by scripts/emit-artifact-module.mjs — do not edit.',
    // JSON string literals are valid JS string literals and round-trip the
    // artifact bytes exactly (template-literal escaping schemes don't).
    `export const shellArtifactJs = ${JSON.stringify(js)};`,
    `export const shellArtifactCss = ${JSON.stringify(css)};`,
    `export const shellArtifactVersion = ${version};`,
    '',
  ].join('\n')
);
writeFileSync(
  join(distDir, 'artifactStrings.d.ts'),
  [
    'export declare const shellArtifactJs: string;',
    'export declare const shellArtifactCss: string;',
    'export declare const shellArtifactVersion: number;',
    '',
  ].join('\n')
);
console.log('wrote dist/artifactStrings.{js,d.ts}');
