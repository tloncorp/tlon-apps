// Renders desk/lib/pet-name.hoon from the pet-name word lists, so the desk's
// public pages name ships as the app does. From packages/api:
//   ../../node_modules/.bin/tsx scripts/petNameHoon.ts
// src/__tests__/petNameHoon.test.ts fails when its word lists are out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import words from '../src/lib/petNameWords.json';

export const PET_NAME_HOON_PATH = fileURLToPath(
  new URL('../../../desk/lib/pet-name.hoon', import.meta.url)
);

const LISTS = [
  'galaxies',
  'adverbs',
  'adjectives',
  'colors',
  'animals',
  'comets',
] as const;

// Words in rows that keep each line within 80 columns after the 6-column
// indent.
function wordList(name: (typeof LISTS)[number]): string {
  const rows: string[] = [];
  let row = '';
  for (const word of words[name]) {
    const cell = `'${word}'`;
    if (row && 6 + row.length + 2 + cell.length > 80) {
      rows.push(row);
      row = '';
    }
    row = row ? `${row}  ${cell}` : cell;
  }
  rows.push(row);
  return [
    `++  ${name}`,
    '  ^~  ^-  (list @t)',
    `  :~  ${rows.join('\n      ')}`,
    '  ==',
  ].join('\n');
}

export function renderPetNameHoon(): string {
  return `::  pet-name: a ship as people see it, when it has no nickname
::
::    Generated by packages/api/scripts/petNameHoon.ts from the frozen word
::    lists (version ${words.version}) in packages/api/src/lib/petNameWords.json;
::    don't edit it by hand. +name matches shipToDisplayId in
::    packages/api/src/lib/urbit.ts: the words index the bytes the @p's
::    syllables spell (after +fein:ob), a moon is a short tag before its
::    parent's name, and a comet is its short form, marked unverified.
::
|%
++  name
  |=  who=ship
  ^-  tape
  =/  x=@  (fein:ob who)
  ?:  (lth who (bex 32))  ['@' (low x)]
  ?:  (lth who (bex 64))
    :(weld "@" (star (end 4 (rsh 5 x))) " \\c2\\b7 " (low (end 5 x)))
  =/  lo=@  (end 5 x)
  ;:  weld
    "@?"
    (comet (cut 3 [3 1] lo))  "."
    (comet (cut 3 [2 1] lo))  "."
    (comet (cut 3 [1 1] lo))  "."
    (comet (cut 3 [0 1] lo))
  ==
::  +low: the name of a scrambled value under 2^32, by its size
::
++  low
  |=  x=@
  ^-  tape
  ?:  (lth x 0x100)  (trip (snag x galaxies))
  ?:  (lth x 0x1.0000)  (star x)
  ;:  weld
    (trip (snag (rsh [3 3] x) adverbs))  "."
    (trip (snag (end [0 9] (rsh [0 15] x)) adjectives))  "."
    (trip (snag (end [0 6] (rsh [0 9] x)) colors))  "."
    (trip (snag (end [0 9] x) animals))
  ==
::  +star: adjective and animal for 16 bits; the animal is the low byte
::
++  star
  |=  x=@
  ^-  tape
  :(weld (trip (snag (rsh 3 x) adjectives)) "." (trip (snag (end 3 x) animals)))
::
++  comet
  |=  b=@
  ^-  tape
  (trip (snag b comets))
::
${LISTS.map(wordList).join('\n::\n')}
--
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(PET_NAME_HOON_PATH, renderPetNameHoon());
}
