// Prints example pet names as markdown. From packages/api:
//   ../../node_modules/.bin/tsx scripts/petNameExamples.ts > scripts/petNameExamples.md
import { render } from '@urbit/aura';

import { shipToPetName } from '../src/lib/petName';
import { shipToDisplayId } from '../src/lib/urbit';
import words from '../src/lib/petNameWords.json';

const out: string[] = [];
const row = (...cells: string[]) => out.push(`| ${cells.join(' | ')} |`);
const table = (title: string, note: string, header: string[]) => {
  out.push('', `## ${title}`, '', ...(note ? [note, ''] : []));
  row(...header);
  row(...header.map(() => '---'));
};
const code = (s: string | null) => '`' + s + '`';
const ship = (n: bigint) => render('p', n);
const basic = (n: bigint) =>
  row(code(ship(n)), shipToDisplayId(ship(n))!, code(shipToPetName(ship(n))));

out.push(
  '# Pet name examples',
  '',
  `Generated by \`scripts/petNameExamples.ts\` from word lists version ${words.version} (${words.status}).`
);

table('Galaxies', 'One word from the 256-word galaxy list.', [
  '@p',
  'Number',
  'Pet name',
]);
for (const n of [0n, 1n, 2n, 3n, 100n, 255n]) basic(n);

table(
  'Stars',
  "Adjective-animal. The animal is the star's low byte, which is its galaxy, so every star under one galaxy shares an animal, just as every star under ~zod ends in `zod`.",
  ['@p', 'Number', 'Pet name']
);
for (const n of [0x100n, 0x200n, 0x300n, 0xff00n, 0x101n, 0x102n, 0x1234n])
  basic(n);

table(
  'Planets',
  'Adverb-adjective-color-animal. The first five are consecutive planets under ~marzod: the @p scramble (`fein`) makes their names unrelated.',
  ['@p', 'Number', 'Pet name']
);
for (const i of [1n, 2n, 3n, 4n, 5n]) basic((i << 16n) | 0x100n);
// ~sampel-palnet, then the planet range's edges.
for (const n of [0x60daf13fn, 0x10000n, 0xffffffffn, 0x12345678n]) basic(n);

table(
  'Moons of ~sampel-palnet',
  `\`<moon part>${' · '}<parent>\`. Full: the moon's high 32 bits as a planet-shaped name (reversible). Tag: 2 words from 16 of those bits (lossy; only the parent's owner can make moons).`,
  ['@p', 'Number', 'Full', 'Tag']
);
for (const high of [1n, 2n, 3n, 0x1234n, 0xdeadbeefn]) {
  const s = ship((high << 32n) | 0x60daf13fn);
  row(
    code(s),
    shipToDisplayId(s)!,
    code(shipToPetName(s)),
    code(shipToPetName(s, { moon: 'tag' }))
  );
}
{
  const s = ship((1n << 32n) | 0x100n);
  row(
    code(s) + ' (moon of a star)',
    shipToDisplayId(s)!,
    code(shipToPetName(s)),
    code(shipToPetName(s, { moon: 'tag' }))
  );
}

table(
  'Comets',
  'Short: the last 4 of 16 comet words, marked `?` (unverified). Full: all 16, reversible, for a profile or details view.',
  ['@p', 'Form', 'Pet name']
);
for (const n of [0xbacbe1fa_e3f3b3a3_0a1b2c3d_4e5f6071n, 2n ** 64n + 0x0100n]) {
  const s = ship(n);
  row(code(s), 'short', code(shipToPetName(s, { comet: 'short' })));
  row('', 'full', code(shipToPetName(s, { comet: 'full' })));
}

// Name lengths, for judging whether 4-word planets are too long.
const longest = (list: string[]) => Math.max(...list.map((w) => w.length));
const mean = (list: string[]) =>
  list.reduce((a, w) => a + w.length, 0) / list.length;
const planetMax =
  longest(words.adverbs) +
  longest(words.adjectives) +
  longest(words.colors) +
  longest(words.animals) +
  3;
const planetMean =
  mean(words.adverbs) +
  mean(words.adjectives) +
  mean(words.colors) +
  mean(words.animals) +
  3;
out.push(
  '',
  '## Lengths',
  '',
  `- Planet names: ${planetMean.toFixed(1)} characters on average, ${planetMax} at most (a planet @p is 13).`,
  `- Star names: ${(mean(words.adjectives.slice(0, 256)) + mean(words.animals.slice(0, 256)) + 1).toFixed(1)} characters on average (a star @p is 6).`,
  `- Mean word length: ${Object.entries(words)
    .filter(([, v]) => Array.isArray(v))
    .map(([k, v]) => `${k} ${mean(v as string[]).toFixed(1)}`)
    .join(', ')}.`,
  ''
);

console.log(out.join('\n'));
